//! The sweeps the report prints and the figures draw.
//!
//! Two questions, kept apart because they have different answers.
//!
//! 1. **When is the gap largest?** That is a question about the truth, and the truth here is
//!    synthetic: both latents converge geometrically, so the gap has a closed form and a half-life.
//!    The simulation checks the algebra rather than discovering anything.
//! 2. **When does the estimate fail?** That is a question about the observations, and it is the one
//!    worth running. The answer depends on the design and on `gamma`, not on time.

use crate::{observability, simulate, static_fit, subtract, Design, Estimate, Kalman, Params};

/// The true gap over the horizon, averaged across seeds so the curve is the model rather than noise.
#[derive(Debug, Clone)]
pub struct GapProfile {
    pub adoption: f64,
    /// True gap by month, averaged.
    pub gap: Vec<f64>,
    /// Month-on-month change in the averaged gap.
    pub growth: Vec<f64>,
    /// Month with the largest gap. Always the last month here, and that is the finding.
    pub peak_month: usize,
    /// Month with the fastest growth, which is the non-obvious one.
    pub fastest_month: usize,
    pub fastest_growth: f64,
}

/// Average the true gap across seeds.
pub fn gap_profile(params: &Params, adoption: f64, seeds: u64) -> GapProfile {
    let mut sum = vec![0.0; params.horizon];
    for seed in 0..seeds {
        let trace = simulate(params, adoption, seed);
        for (index, value) in trace.gap().iter().enumerate() {
            sum[index] += value;
        }
    }
    let gap: Vec<f64> = sum.iter().map(|s| s / seeds as f64).collect();
    let growth: Vec<f64> = gap.windows(2).map(|pair| pair[1] - pair[0]).collect::<Vec<_>>();

    let peak_month = gap
        .iter()
        .enumerate()
        .max_by(|a, b| a.1.partial_cmp(b.1).unwrap())
        .map(|(i, _)| i + 1)
        .unwrap_or(0);
    let (fastest_month, fastest_growth) = growth
        .iter()
        .enumerate()
        .max_by(|a, b| a.1.partial_cmp(b.1).unwrap())
        .map(|(i, v)| (i + 2, *v))
        .unwrap_or((0, 0.0));

    GapProfile { adoption, gap, growth, peak_month, fastest_month, fastest_growth }
}

/// One cell of the design sweep.
#[derive(Debug, Clone, PartialEq)]
pub struct Cell {
    pub adoption: f64,
    pub gamma: f64,
    pub design: Design,
    /// True gap at the last month, averaged over seeds.
    pub true_gap_end: f64,
    pub rank: usize,
    pub condition: f64,
    pub kalman_rmse: f64,
    pub subtraction_rmse: f64,
    pub static_rmse: f64,
    /// RMSE of the filter's own process model with no observations at all.
    pub prior_only_rmse: f64,
    pub kalman_coverage: f64,
    /// How far the world's assistance effects exceeded the filter's assumption.
    pub mismatch: f64,
}

impl Cell {
    /// Filter error relative to the baseline it has to beat. Below one means the filter helps.
    pub fn gain_over_subtraction(&self) -> f64 {
        self.kalman_rmse / self.subtraction_rmse
    }

    /// True when the design cannot recover both latents, whatever the estimator does.
    pub fn unidentifiable(&self) -> bool {
        self.rank < 2
    }

    /// Filter error relative to its own model with no data.
    ///
    /// Near 1.0 means the filter is not reading the observations: its process model is carrying the
    /// estimate. That is the failure a simulation of a simulation hides, because the truth is
    /// generated by the same transition the filter assumes.
    pub fn gain_over_prior(&self) -> f64 {
        self.kalman_rmse / self.prior_only_rmse
    }
}

/// Evaluate one cell, with the truth generated under different dynamics from the filter's.
///
/// `kappa_mismatch` is the fraction by which the world's assistance effects exceed the filter's
/// assumption. At zero the filter's process model is exactly right — which is what any simulation
/// with a single parameter set gives it — and at zero the comparison is rigged in the filter's
/// favour by construction. Raising it is the only way to ask whether the filter reads the data.
pub fn evaluate_mismatched(
    params: &Params,
    adoption: f64,
    gamma: f64,
    design: Design,
    seeds: u64,
    kappa_mismatch: f64,
) -> Cell {
    let mut filter = params.clone();
    filter.gamma = gamma;

    let mut truth = filter.clone();
    truth.kappa_a *= 1.0 + kappa_mismatch;
    truth.kappa_b *= 1.0 + kappa_mismatch;

    let obs = observability(&filter, design, adoption);

    let (kalman_rmse, kalman_coverage, true_gap_end) =
        run_rmse_split(&truth, &filter, adoption, seeds, |trace, f| {
            let mut kal = Kalman::new(f, design, adoption);
            kal.run(trace)
        });
    let (prior_only_rmse, _, _) = run_rmse_split(&truth, &filter, adoption, seeds, |_, f| {
        let mut kal = Kalman::new(f, design, adoption);
        kal.run_prior_only(f.horizon)
    });
    let (subtraction_rmse, _, _) =
        run_rmse_split(&truth, &filter, adoption, seeds, |trace, f| subtract(trace, f));
    let (static_rmse, _, _) =
        run_rmse_split(&truth, &filter, adoption, seeds, |trace, f| static_fit(trace, f, design));

    Cell {
        adoption,
        gamma,
        design,
        true_gap_end,
        rank: obs.rank,
        condition: obs.condition,
        kalman_rmse,
        subtraction_rmse,
        static_rmse,
        prior_only_rmse,
        kalman_coverage,
        mismatch: kappa_mismatch,
    }
}

/// As [`evaluate_mismatched`] with the world and the filter agreeing.
pub fn evaluate(params: &Params, adoption: f64, gamma: f64, design: Design, seeds: u64) -> Cell {
    evaluate_mismatched(params, adoption, gamma, design, seeds, 0.0)
}

/// RMSE with the trace generated by `truth` and the estimator built from `filter`.
fn run_rmse_split<F>(
    truth_params: &Params,
    filter_params: &Params,
    adoption: f64,
    seeds: u64,
    mut make: F,
) -> (f64, f64, f64)
where
    F: FnMut(&crate::Trace, &Params) -> Estimate,
{
    let mut rmse_total = 0.0;
    let mut coverage_total = 0.0;
    let mut gap_end = 0.0;
    for seed in 0..seeds {
        let trace = simulate(truth_params, adoption, seed);
        let truth = trace.gap();
        let estimate = make(&trace, filter_params);
        if estimate.gap.iter().any(|v| !v.is_finite()) {
            return (f64::INFINITY, 0.0, f64::NAN);
        }
        rmse_total += estimate.rmse(&truth);
        coverage_total += estimate.coverage(&truth);
        gap_end += truth.last().copied().unwrap_or(0.0);
    }
    let n = seeds as f64;
    (rmse_total / n, coverage_total / n, gap_end / n)
}

/// The full grid, including the dynamics-mismatch axis.
pub fn sweep_with_mismatch(
    params: &Params,
    adoptions: &[f64],
    gammas: &[f64],
    designs: &[Design],
    seeds: u64,
    mismatches: &[f64],
) -> Vec<Cell> {
    let mut cells = Vec::new();
    for &mismatch in mismatches {
        for &adoption in adoptions {
            for &gamma in gammas {
                for &design in designs {
                    cells.push(evaluate_mismatched(
                        params, adoption, gamma, design, seeds, mismatch,
                    ));
                }
            }
        }
    }
    cells
}

/// The grid at zero mismatch.
pub fn sweep(
    params: &Params,
    adoptions: &[f64],
    gammas: &[f64],
    designs: &[Design],
    seeds: u64,
) -> Vec<Cell> {
    sweep_with_mismatch(params, adoptions, gammas, designs, seeds, &[0.0])
}
